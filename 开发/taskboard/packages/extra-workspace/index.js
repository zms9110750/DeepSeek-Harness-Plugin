/**
 * 任务板 · 额外的工作空间（占位）。
 *
 * 用户要求拆八块，这是第 ⑧ 块：
 *   > 8.额外的工作空间（这个打占位。版本0.0.1-a.0）
 *
 * 版本按用户要求定为 `0.0.1-a.0` —— 这是占位标记，不是能用的组件。
 *
 * ## 打算做什么（还没实现）
 *
 * 现在「子工作空间」把可写范围限制在**一个**目录里（任务的 `workspace` 字段）。
 * 但真实工作经常需要同时读另外几个地方：
 *
 *   · 主战场是一个仓库，但要读同机的另一个项目当参考
 *   · 任务的数据在 A 目录，但脚本在 B 目录
 *   · 模板 / 素材放在第三个地方
 *
 * 所以任务加一个 `workspaces` 字段（复数，逗号分隔的绝对路径），
 * 与主工作空间并列，一起参与可写范围判定。
 *
 * ## 为什么单独成包
 *
 * 「子工作空间」负责**主战场**的语义（一个目录、权限档、写范围）。
 * 「额外工作空间」负责**并列的其它目录**，判定规则不一样：
 *
 *   · 子工作空间：这是你干活的地方，可写
 *   · 额外工作空间：这是你**需要够得着**的地方，是否可写要另外判
 *
 * 两者混在一个包里会让「哪些路径可写」这条规则变模糊。
 */

