/**
 * ⑤ search —— 搜索条件。
 *
 * 条件必须是**纯数据**、可 JSON 序列化 —— 因为它要跨「浏览器 → 宿主」这条边界：
 * ⑩ 的搜索框把条件序列化发给宿主，宿主侧调 ⑤，结果回传渲染。
 * 这也是"可序列化"这条要求的原始理由（docs 2.2）。
 *
 * ## 只有四项，零扩展位
 *
 * 用户 `2026-11-01 13:18`：
 * 「搜索可以搜标题，编号。然后还提供对状态，分组，领域的筛选。
 *   只不过，前者在ui上是搜索框。后者是按钮。在ai tool上是一个方法。可以进行搜索的时候同时筛选。」
 *
 * ⇒ 关键词（搜索框）+ 状态 / 分组 / 领域（三个按钮），**就这四项**。
 * 我曾在此处放过 `kind` / `template` / `parent` / `tags` / `flags` 五个"扩展位" ——
 * 其中 `tags` / `flags` 是我从旧版 core 残留印象里带进来的，**没有任何上游依据**，已全部删除。
 */

/**
 * 一份搜索条件。
 *
 * 字段之间 **AND**；同一字段内的数组之间 **OR**。
 * 空条件（`{}`）= 返回全集。
 */
export interface SearchCondition {
	/**
	 * 关键词，匹配**标题**与**编号**（不匹配正文/备注）。
	 *
	 * 大小写、空格怎么处理由 ⑤ 决定：当前**不折叠大小写、不 trim** ——
	 * 与 `domain` 的处理保持一致（存什么比什么）。
	 */
	readonly keyword?: string;

	/** 状态。元素是状态字符串，由调用方把"组"展开成列表。 */
	readonly status?: readonly string[];

	/** 分组 = 状态组（提交 / 处理 / 搁置 / 完成）。同样由调用方展开成状态列表。 */
	readonly group?: readonly string[];

	/**
	 * 领域。匹配 `card.template.domain`。
	 *
	 * 存的是中文字符串（`核心` / `代码`），**精确比较**：
	 * **不 trim、不做大小写折叠、不做别名合并** ——
	 * 归一化会让"存的值"与"筛的值"分属两套口径（docs 2.3）。
	 */
	readonly domain?: readonly string[];
}
