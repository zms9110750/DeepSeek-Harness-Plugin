/**
 * ⑤ search —— 搜索条件。
 *
 * 条件必须是**纯数据**、可 JSON 序列化 —— 因为它要跨「浏览器 → 宿主」这条边界：
 * ⑩ 的搜索框把条件序列化发给宿主，宿主侧调 ⑤，结果回传渲染。
 * 这也是"可序列化"这条要求的原始理由（docs 2.2）。
 *
 * ## 五项，全部来自用户 `2026-11-02 17:37`
 *
 * > 「搜索包提供的搜索api，他的参数应该是一个对象。
 * >   包括标题模糊搜索，还有领域，分类，状态，模板的筛选。
 * >   因为ui和tool有可能点了筛选按钮组过滤的情况下输入搜索栏。」
 *
 * ⇒ **标题模糊搜索** 1 项 + **领域 / 分类 / 状态 / 模板** 4 项筛选 = 5 项。
 * **筛选与搜索框可以同时用** ⇒ 字段之间 **AND**。
 *
 * ## ⚠ 三处与上一版不同（都已被用户推翻）
 *
 * 1. **`keyword` → `title`**：只搜**标题**。
 *    **编号不在 ⑤ 里搜** —— 用户：「精确搜索由 core 提供。参数是编号。」
 *    ⇒ 按编号取卡是 ⑧ 的 `get(cardId)`（精确查），不是模糊搜。
 *
 * 2. **`group` 删除**：用户：「搜索不需要维护。桥阶层和ui层维护就行了。」
 *    ⇒ **状态组的展开（如「进行」→ `[SUBMITTED, WORKING]`）归 ⑨⑩ 这些桥接层**，
 *    ⑤ **不收「组」**，只收展开后的 `status` 列表。这一条是**职责边界**，不是漏写。
 *
 * 3. **新增 `kind` / `template`**：上一版我把它们当"无依据的扩展位"删掉了 ——
 *    现在用户点名要，它们是**有依据的正式筛选维度**。
 */

/**
 * 一份搜索条件。
 *
 * **字段之间 AND**；同一字段内的数组之间 **OR**。
 * 空条件（`{}`）= 返回全集。
 *
 * 例：`{ title: ['登录'], kind: ['work'] }` = 「标题含『登录』」**且**「分类是工作」。
 * 例：`{ title: ['登录', '注册'] }` = 「标题含『登录』**或**含『注册』」（同一字段内 OR）。
 */
export interface SearchCondition {
	/**
	 * 标题**模糊**搜索（子串匹配）。**不匹配编号**（编号走 ⑧ 的精确搜索）。
	 *
	 * **同一字段内 OR**：`['foo', 'bar']` = 标题含 foo **或** 含 bar（用户 `2026-11-02 17:50`「都是or」）。
	 *
	 * **不折叠大小写、不 trim** —— 与 `domain` 同一处理口径（存什么比什么）。
	 */
	readonly title?: readonly string[];

	/**
	 * 领域。匹配 `card.template.domain`。
	 *
	 * 存的是中文字符串（`核心` / `代码`），**精确比较**：
	 * 不 trim、不做大小写折叠、不做别名合并 ——
	 * 归一化会让"存的值"与"筛的值"分属两套口径（docs 2.3）。
	 */
	readonly domain?: readonly string[];

	/** 分类（`goal` / `design` / `record` / `work`）。匹配 `card.template.kind`。**精确比较。** */
	readonly kind?: readonly string[];

	/**
	 * 状态。匹配 `card.status`。**精确比较。**
	 *
	 * ⚠ 这里收的是**状态列表**，不是"组" —— 组由 ⑨⑩ 展开（见文件头第 2 条）。
	 */
	readonly status?: readonly string[];

	/** 模板。匹配 `card.template.ref`（模板 name）。**精确比较。** */
	readonly template?: readonly string[];
}
